def test_json_defaults_are_not_shared_and_top_level_mutations_persist(
    engine: Engine,
) -> None:
    with Session(engine) as session:
        first = WorkflowTask(
            id="industrial_design_first",
            user_id="user-1",
            status="queued",
            progress=0,
            current_step="created",
            events=[
                WorkflowTaskEvent(
                    sequence=1,
                    event_type="status",
                    status="queued",
                    progress=0,
                    message="created",
                )
            ],
        )
        second = WorkflowTask(
            id="industrial_design_second",
            user_id="user-1",
            status="queued",
            progress=0,
            current_step="created",
        )
        asset = Asset(
            user_id="user-1",
            task=first,
            kind="cad",
            filename="mutable.step",
            content_type="application/step",
            size_bytes=3,
            sha256="9" * 64,
            chunk_size=3,
            chunk_count=1,
            status="ready",
            source="generated",
        )
        workspace = WorkspaceState(user_id="user-json")
        session.add_all([first, second, asset, workspace])
        session.flush()

        first.input_payload["prompt"] = "bearing housing"
        first.design_spec["material"] = "steel"
        first.outputs["asset_id"] = str(asset.id)
        first.diagnostics.append({"code": "queued"})
        first.events[0].event_data["worker"] = "local"
        asset.asset_metadata["generator"] = "jscad"
        workspace.state_data["panel"] = "workflow"
        session.commit()
        asset_id = asset.id
        workspace_id = workspace.id

    with Session(engine) as verification_session:
        persisted_first = verification_session.get(
            WorkflowTask,
            "industrial_design_first",
        )
        persisted_second = verification_session.get(
            WorkflowTask,
            "industrial_design_second",
        )
        assert persisted_first is not None
        assert persisted_second is not None
        assert persisted_first.input_payload == {"prompt": "bearing housing"}
        assert persisted_first.design_spec == {"material": "steel"}
        assert persisted_first.outputs == {"asset_id": str(asset_id)}
        assert persisted_first.diagnostics == [{"code": "queued"}]
        assert persisted_first.events[0].event_data == {"worker": "local"}
        assert persisted_second.input_payload == {}
        assert persisted_second.diagnostics == []
        persisted_asset = verification_session.get(Asset, asset_id)
        persisted_workspace = verification_session.get(WorkspaceState, workspace_id)
        assert persisted_asset is not None
        assert persisted_workspace is not None
        assert persisted_asset.asset_metadata == {"generator": "jscad"}
        assert persisted_workspace.state_data == {"panel": "workflow"}


