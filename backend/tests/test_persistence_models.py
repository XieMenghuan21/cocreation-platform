def test_version_asset_reference_migration_preserves_legacy_path_values(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    backend_dir = Path(__file__).resolve().parents[1]
    database_url = f"sqlite+pysqlite:///{tmp_path / 'legacy-paths.db'}"
    monkeypatch.setattr(settings, "DATABASE_URL", database_url)
    config = Config(backend_dir / "alembic.ini")
    command.upgrade(config, "20260723_0001")
    migration_engine = create_engine(database_url)
    now = "2026-07-24 00:00:00+00:00"
    with migration_engine.begin() as connection:
        connection.execute(
            text(
                """
                INSERT INTO cocreation_project_histories (
                    id, user_id, project_id, project_name, created_at, updated_at,
                    project_data
                ) VALUES (
                    1, 'alice', 'legacy-project', 'Legacy Project', :now, :now, '{}'
                )
                """
            ),
            {"now": now},
        )
        connection.execute(
            text(
                """
                INSERT INTO cocreation_project_version_histories (
                    project_history_id, user_id, version_id, label, status, note,
                    is_finalized, generated_image_urls, script_path, work_dir,
                    output_path, created_at, model_objects, parameters,
                    generated_assets, diagnostics, snapshot_data, updated_at
                ) VALUES (
                    1, 'alice', 'v1', 'Legacy', 'completed', 'legacy', 1, '[]',
                    '/legacy/model.js', '/legacy/work', '/legacy/output.step',
                    :now, '[]', '[]', '[]', '[]', '{}', :now
                )
                """
            ),
            {"now": now},
        )

    command.upgrade(config, "head")
    columns = {
        column["name"]
        for column in inspect(migration_engine).get_columns(
            "cocreation_project_version_histories"
        )
    }
    assert {"script_path", "work_dir", "output_path"} <= columns
    assert {"script_asset_id", "output_asset_id"} <= columns
    with migration_engine.connect() as connection:
        upgraded = connection.execute(
            text(
                """
                SELECT script_path, work_dir, output_path
                FROM cocreation_project_version_histories
                WHERE version_id = 'v1'
                """
            )
        ).one()
    assert tuple(upgraded) == (
        "/legacy/model.js",
        "/legacy/work",
        "/legacy/output.step",
    )

    command.downgrade(config, "20260723_0001")
    downgraded_columns = {
        column["name"]
        for column in inspect(migration_engine).get_columns(
            "cocreation_project_version_histories"
        )
    }
    assert {"script_path", "work_dir", "output_path"} <= downgraded_columns
    assert "script_asset_id" not in downgraded_columns
    assert "output_asset_id" not in downgraded_columns
    with migration_engine.connect() as connection:
        downgraded = connection.execute(
            text(
                """
                SELECT script_path, work_dir, output_path
                FROM cocreation_project_version_histories
                WHERE version_id = 'v1'
                """
            )
        ).one()
    assert tuple(downgraded) == tuple(upgraded)
    command.downgrade(config, "base")
    migration_engine.dispose()


