def test_asset_chunk_index_is_unique_within_asset(engine: Engine) -> None:
    with Session(engine) as session:
        asset = Asset(
            user_id="user-1",
            kind="cad",
            filename="model.step",
            content_type="application/step",
            size_bytes=6,
            sha256="a" * 64,
            chunk_size=3,
            chunk_count=2,
            status="ready",
            source="upload",
        )
        asset.chunks.extend(
            [
                AssetBlobChunk(
                    chunk_index=0,
                    size_bytes=3,
                    sha256="b" * 64,
                    content=b"abc",
                ),
                AssetBlobChunk(
                    chunk_index=0,
                    size_bytes=3,
                    sha256="c" * 64,
                    content=b"def",
                ),
            ]
        )
        session.add(asset)

        with pytest.raises(IntegrityError):
            session.commit()

        session.rollback()
        valid_asset = Asset(
            user_id="user-2",
            kind="cad",
            filename="valid.step",
            content_type="application/step",
            size_bytes=3,
            sha256="d" * 64,
            chunk_size=3,
            chunk_count=1,
            status="ready",
            source="upload",
            chunks=[
                AssetBlobChunk(
                    chunk_index=0,
                    size_bytes=3,
                    sha256="e" * 64,
                    content=b"ghi",
                )
            ],
        )
        session.add(valid_asset)
        session.commit()
        valid_asset_id = valid_asset.id

    with Session(engine) as verification_session:
        persisted_asset = verification_session.get(Asset, valid_asset_id)
        assert persisted_asset is not None
        assert len(persisted_asset.chunks) == 1


